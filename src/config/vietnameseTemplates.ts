export const VIETNAMESE_BIG_WISHES = (name: string, relationship: string, interests: string[] = []) => {
    const wishes = [
        { emoji: "🚀", wish: `Chúc ${name} một tuổi mới bứt phá và gặt hái thật nhiều thành công!` },
        { emoji: "💎", wish: `${name} là một điều quý giá. Cứ tiếp tục toả sáng theo cách của mình nhé.` },
    ];
    if (relationship === 'partner') {
        wishes.push(
            { emoji: "❤️", wish: `Mỗi nhịp tim này đều chúc ${name} thật nhiều hạnh phúc và bình an.` },
            { emoji: "💍", wish: `Mong hành trình của chúng ta cứ đẹp mãi như thế.` },
        );
    } else if (relationship === 'friend') {
        wishes.push(
            { emoji: "🔥", wish: `Cứ sống hết mình và chinh phục thế giới nhé, ${name}!` },
            { emoji: "🍻", wish: `Mừng cho mọi kỷ niệm đã có và tình bạn này, thứ tôi không muốn mất.` },
        );
    } else if (relationship === 'colleague' || relationship === 'mentor') {
        wishes.push(
            { emoji: "🌿", wish: `Chúc ${name} một tuổi mới cân bằng, ít họp hơn và ít việc gấp hơn.` },
            { emoji: "☕", wish: `Chúc ${name} luôn nhiều năng lượng và thật nhiều thời gian cho những thứ mình thích.` },
        );
    }
    if (interests.some(i => i.toLowerCase().includes('car'))) {
        wishes.push({ emoji: "🏎️", wish: `Chúc cuộc sống của ${name} tăng tốc mượt mà trên đường đua hạnh phúc!` });
    }
    if (interests.some(i => i.toLowerCase().includes('coding'))) {
        wishes.push({ emoji: "💻", wish: `Chúc ${name} một năm không bug, chỉ toàn feature vui!` });
    }
    return wishes;
};
